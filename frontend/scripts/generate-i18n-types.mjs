import { createHash } from "node:crypto";
import { readFile, writeFile } from "node:fs/promises";
import path from "node:path";
import { fileURLToPath } from "node:url";
import { namespaces } from "./i18n-config.mjs";

const root = path.resolve(path.dirname(fileURLToPath(import.meta.url)), "..");
const localeRoot = path.join(root, "src", "i18n", "locales", "en");
const outputPath = path.join(root, "src", "i18n", "i18next.generated.d.ts");
const checkOnly = process.argv.includes("--check");
const interpolationPattern = /{{\s*([A-Za-z_$][\w$]*)\s*(?:,[^}]*)?}}/g;

function quote(value) {
  return JSON.stringify(value);
}

function toType(value, indent = "      ") {
  if (typeof value === "string") return quote(value);
  const entries = Object.entries(value);
  if (entries.length === 0) return "Record<string, never>";
  const nextIndent = `${indent}  `;
  return `{\n${entries
    .map(([key, child]) => `${nextIndent}${quote(key)}: ${toType(child, nextIndent)};`)
    .join("\n")}\n${indent}}`;
}

function flatten(value, prefix = "", result = new Map()) {
  for (const [key, child] of Object.entries(value)) {
    const next = prefix ? `${prefix}.${key}` : key;
    if (typeof child === "string") result.set(next, child);
    else flatten(child, next, result);
  }
  return result;
}

const resources = {};
for (const namespace of namespaces) {
  resources[namespace] = JSON.parse(
    await readFile(path.join(localeRoot, `${namespace}.json`), "utf8"),
  );
}

const sourceHash = createHash("sha256")
  .update(JSON.stringify(resources))
  .digest("hex");
const allKeys = [];
const paramLines = [];
for (const namespace of namespaces) {
  for (const [key, message] of flatten(resources[namespace])) {
    const qualified = `${namespace}:${key}`;
    allKeys.push(qualified);
    const params = [...message.matchAll(interpolationPattern)].map(
      (match) => match[1],
    );
    const uniqueParams = [...new Set(params)];
    const type = uniqueParams.length
      ? `{ ${uniqueParams.map((name) => `${quote(name)}: string | number | boolean`).join("; ")} }`
      : "Record<string, never>";
    paramLines.push(`  ${quote(qualified)}: ${type};`);
  }
}

const generated = `// Generated by scripts/generate-i18n-types.mjs. Do not edit.
// Source SHA-256: ${sourceHash}
import "i18next";

export type TranslationKey =
${allKeys.map((key) => `  | ${quote(key)}`).join("\n")};

export interface TranslationParams {
${paramLines.join("\n")}
}

declare module "i18next" {
  interface CustomTypeOptions {
    defaultNS: "common";
    returnNull: false;
    resources: {
${namespaces
  .map(
    (namespace) =>
      `      ${quote(namespace)}: ${toType(resources[namespace], "      ")};`,
  )
  .join("\n")}
    };
  }
}
`;

if (checkOnly) {
  const current = await readFile(outputPath, "utf8").catch(() => "");
  if (current !== generated) {
    console.error(
      "i18next.generated.d.ts is stale. Run npm run generate:i18n-types.",
    );
    process.exit(1);
  }
} else {
  await writeFile(outputPath, generated, "utf8");
}
